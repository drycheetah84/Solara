#!/usr/bin/env bash
# Extracts the secrets that the original Halcyon backend hard-coded into its C# source
# into config/legacy-secrets.env (git-ignored), so Solara keeps identical credentials
# (shared with the deployed game-server DLL, existing JWTs, the encrypted DB) without
# copying them into Go source. Usage: tools/scripts/extract-legacy-secrets.sh <halcyon backend/src dir>
set -euo pipefail
SRC="${1:-reference/halcyon/backend/src}"
OUT="${2:-config/legacy-secrets.env}"
val() { # file, perl regex capturing the value
  perl -ne "if (/$2/) { print \$1; exit }" "$SRC/$1"
}
MS=AUnrealFeatures.AAMothership/MothershipServer.cs
SD=AUnrealFeatures.Ares/Servers/A2StationDbServer.cs
EG=AUnrealFeatures.EOSSDK/AUnrealFeatures.EOSSDK/EosGatewayServer.cs
RT=AUnrealFeatures.EOSSDK/AUnrealFeatures.EOSSDK/RtcHelper.cs
PG=AUnrealFeatures.Ares/Program.cs
umask 077
mkdir -p "$(dirname "$OUT")"
{
  echo "# Generated by tools/scripts/extract-legacy-secrets.sh from the original Halcyon source."
  echo "# DO NOT COMMIT. Values may be overridden by environment variables SOLARA_<NAME>."
  echo "JWT_SECRET=$(val $MS 'const string JWT_SECRET\s*=\s*"([^"]*)"')"
  echo "META_APP_SECRET=$(val $MS 'const string META_APP_SECRET\s*=\s*"([^"]*)"')"
  echo "AUTOMATION_KEY=$(val $MS 'const string AUTOMATION_KEY\s*=\s*"([^"]*)"')"
  echo "SERVER_API_KEY=$(val $MS 'return "([0-9a-f]{32,})";')"
  echo "ServerMasterKey=$(val $SD 'const string ServerMasterKey\s*=\s*"([^"]*)"')"
  echo "QUEST_APP_SECRET=$(val $SD 'const string QUEST_APP_SECRET\s*=\s*"([^"]*)"')"
  echo "TURN_SECRET=$(val $EG 'const string TURN_SECRET\s*=\s*"([^"]*)"')"
  echo "RTC_API_KEY=$(val $RT 'const string API_KEY\s*=\s*"([^"]*)"')"
  echo "RTC_API_SECRET=$(val $RT 'const string API_SECRET\s*=\s*"([^"]*)"')"
  echo "PRODUCTION_DB_PASSWORD=$(val $PG 'password\s*=\s*"([^"]+)"')"
} > "$OUT"
echo "wrote $OUT ($(grep -c '=.' "$OUT") entries)"
grep -E '^[A-Za-z_]+=$' "$OUT" && { echo "ERROR: empty values above" >&2; exit 1; } || true
