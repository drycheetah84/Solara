#!/usr/bin/env python3
import json

d = json.load(open("worksheet.json"))
rows = d["rows"]


def h(v):
    try:
        return hex(int(v))
    except (ValueError, TypeError):
        return v or "?"


out = []
w = out.append
w("# HalcyonA2 DLL offset port -- build 22284 -> 47031 (UE 5.4.2 -> 5.5.3)\n")
w("Generated by tools/a2port. OLD = SpecEditorBuild (22284, 166,994,432 B); "
  "NEW = build 47031 (184,868,864 B). dllmain.cpp holds the live 22284 values.\n")
w("**Status: NOT a finished port.** Signature candidates and IDA-find targets below are "
  "UNVERIFIED. Every code RVA must be confirmed in IDA (function bounds + string xrefs + "
  "decompile) and then runtime crash-tested by injection before it is trusted -- a stale "
  "code RVA is a silent heap-corrupting fast-fail, not a clean crash (per the port guide).\n")

w("## 1. Engine globals -- ground truth from the 47031 Dumper-7 SDK (verified)\n")
w("| global | 47031 RVA |\n|---|---|")
for k, v in d["sdk_globals"].items():
    w(f"| {k} | {v} |")
w("\nThe DLL consumes the typed Dumper-7 SDK (`SDK::UObject::GObjects`, `o->ProcessEvent`), so "
  "**struct member offsets port by repointing the project's SDK include from "
  "`gamesdk/22284` to `C:\\Dumper-7\\5.5.3-47031+++A2+hotfix-A2\\CppSDK\\SDK`** and rebuilding. "
  "Only the 4 hardcoded `_Off` constants and inline member literals need manual re-check vs the "
  "new SDK headers.\n")

w("## 2. Signature candidates (UNVERIFIED -- confirm in IDA, then runtime-test)\n")
w(f"{sum(1 for r in rows if r['status']=='CANDIDATE')} unique signature matches 22284->47031. "
  "A unique strict hit can still be a coincidental prologue match; verify each.\n")
w("| name | 22284 | 47031 candidate | what it is |\n|---|---|---|---|")
seen = set()
for r in rows:
    if r["status"] == "CANDIDATE" and r["name"] not in seen:
        seen.add(r["name"])
        w(f"| {r['name']} | {r['old']} | {h(r['new'])} | {r['note']} |")

w("\n## 3. Ambiguous (multiple signature hits -- disambiguate in IDA)\n")
w("| name | 22284 | hits | what it is |\n|---|---|---|---|")
seen = set()
for r in rows:
    if r["status"] == "AMBIGUOUS" and r["name"] not in seen:
        seen.add(r["name"])
        w(f"| {r['name']} | {r['old']} | {r['new']} | {r['note']} |")

w("\n## 4. Data globals -- resolve via IDA xrefs (no signature possible)\n")
w("| name | 22284 | what it is |\n|---|---|---|")
for r in rows:
    if r["status"] == "IDA-DATA":
        w(f"| {r['name']} | {r['old']} | {r['note']} |")

w("\n## 5. No signature match -- manual IDA reversing required\n")
w("Engine funcs recompiled across 5.4->5.5 and heavily-changed game code. Re-find by string "
  "xref / vtable slot / caller, as the PORT-AUDIT notes in dllmain.cpp describe.\n")
w("| name | 22284 | what it is |\n|---|---|---|")
for r in rows:
    if r["status"] == "IDA-FIND":
        w(f"| {r['name']} | {r['old']} | {r['note']} |")

w("\n## 6. Why this cannot be finished unattended\n")
w("- ~43 functions have no signature match and need interactive IDA reversing (find the A2 "
  "function by its string/vtable, not by a byte pattern).\n"
  "- 17 data globals need IDA xref tracing from ported functions.\n"
  "- All 27 candidates need IDA confirmation AND runtime verification.\n"
  "- The only real proof is injecting into the running game + backend and watching the "
  "crash-driven stabilization loop. That needs the game running and a human watching; it is "
  "not safe to do unattended, and a wrong RVA corrupts the game's heap.\n")
w("## 7. Next steps (with the game + IDA, interactively)\n")
w("1. Repoint the SDK include to the 47031 CppSDK; rebuild to shake out struct/API changes.\n"
  "2. Load NEW A2-Win64-Shipping.exe in IDA (idat64, auto-analysis); confirm each candidate "
  "by function bounds + decompile vs the 22284 source behaviour.\n"
  "3. For section 5, re-find by string xref / vtable slot per the dllmain PORT-AUDIT notes.\n"
  "4. For section 4, xref the data globals from the now-known function bodies.\n"
  "5. Gate dllmain with `g_bootSpineOnly` / `[PORT] STOP HERE return;` and move it down past "
  "each subsystem as its RVAs are confirmed, so stale RVAs can never fire.\n"
  "6. Inject and run the crash-stabilization loop; bake only runtime-verified values.\n")

open("PORT-47031.md", "w", encoding="utf-8").write("\n".join(out))
print("wrote PORT-47031.md", sum(len(x) for x in out), "bytes;", d["summary"])
